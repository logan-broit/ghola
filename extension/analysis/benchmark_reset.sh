#!/bin/bash
# Reset retrieval-time state for BENCHMARK DATA ONLY.
# Usage: ./analysis/benchmark_reset.sh
#
# SAFETY: Only touches mnemes/associations tagged with bench_00000000.
# Real user memories are NEVER modified by this script.
#
# Resets:
#   - access_count (ACT-R base-level activation) to 1 for bench mnemes
#   - last_access to created_at (ACT-R decay baseline) for bench mnemes
#   - co_activation_queue (pending co-activation events)
#   - hebbian associations between bench mnemes
#
# Preserves:
#   - ALL non-benchmark mnemes and their associations
#   - supersedes associations (gating-time knowledge updates)
#   - mneme content, embeddings, entities, clusters, tsvectors

set -euo pipefail

BENCH_TAG="bench_00000000"

echo "Resetting retrieval-time state for benchmark data (tag: $BENCH_TAG)..."
kubectl exec -n ch-system memory-db-1 -- psql -U postgres -d memories -c "
BEGIN;

-- Clear co-activation queue (shared, but only generated by benchmark runs)
TRUNCATE ghola.co_activation_queue;

-- Delete hebbian associations between benchmark mnemes only
DELETE FROM ghola.associations
WHERE association_type = 'hebbian'
  AND src_id IN (SELECT id FROM ghola.mnemes WHERE tags @> ARRAY['$BENCH_TAG']::text[])
  AND dst_id IN (SELECT id FROM ghola.mnemes WHERE tags @> ARRAY['$BENCH_TAG']::text[]);

-- Reset access_count and last_access for benchmark mnemes only
UPDATE ghola.mnemes
SET access_count = 1, last_access = created_at
WHERE tags @> ARRAY['$BENCH_TAG']::text[];

COMMIT;"

echo "Verifying..."
kubectl exec -n ch-system memory-db-1 -- psql -U postgres -d memories -t -A -c "
SELECT 'bench_mnemes: ' || count(*) FILTER (WHERE tags @> ARRAY['$BENCH_TAG']::text[]) ||
       ', real_mnemes: ' || count(*) FILTER (WHERE NOT (tags @> ARRAY['$BENCH_TAG']::text[])) ||
       ', bench_assoc: ' || (SELECT count(*) FROM ghola.associations a
                             JOIN ghola.mnemes m ON a.src_id = m.id
                             WHERE m.tags @> ARRAY['$BENCH_TAG']::text[]) ||
       ', real_assoc: ' || (SELECT count(*) FROM ghola.associations a
                            JOIN ghola.mnemes m ON a.src_id = m.id
                            WHERE NOT (m.tags @> ARRAY['$BENCH_TAG']::text[]))
FROM ghola.mnemes;"

echo "Reset complete. Real memories untouched."
